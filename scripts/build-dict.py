"""Build the dictionary from SCOWL lists (levels 10-70, American + English spellings).
Output:
  data/words.json      {word: tier} used at build time for static word-list pages
  public/words.<hash>.txt  compact list for the in-browser solvers: lines grouped by tier ("#10", "#20", ...)
Tier = the SCOWL size level where the word first appears: 10-35 common, 40-50 less common, 55-70 rare.
"""
import json, re, pathlib, unicodedata
here = pathlib.Path(__file__).parent
root = here.parent
block_exact, block_roots = set(), []
for ln in (here / "blocklist.txt").read_text().splitlines():
    ln = ln.strip()
    if not ln or ln.startswith("#"): continue
    for tok in ln.split():
        if tok.startswith("~"): block_roots.append(tok[1:])
        else: block_exact.add(tok)
def blocked(w): return w in block_exact or any(r in w for r in block_roots)

def ascii_fold(w):
    # café -> cafe, naïve -> naive (word games ignore accents)
    return unicodedata.normalize("NFKD", w).encode("ascii", "ignore").decode()

tier = {}
for lvl in [10, 20, 35, 40, 50, 55, 60, 70]:
    # British spellings (colour, theatre) are valid in most word games but are listed as less common for a US audience.
    for v, floor in [("english", 0), ("american", 0), ("british", 40)]:
        for w in json.load(open(here / "scowl" / f"{v}-words-{lvl}.json")):
            w = ascii_fold(w)
            if re.fullmatch(r"[a-z]{2,15}", w) and not blocked(w):
                t = max(lvl, floor)
                if t < tier.get(w, 99): tier[w] = t
# Two-letter words commonly allowed in North American word games, missing from SCOWL's common levels.
TWO = "aa ab ad ae ag ah ai al am an ar as at aw ax ay ba be bi bo by da de do ed ef eh el em en er es ew ex fa fe gi go ha he hi hm ho id if in is it jo ka ki la li lo ma me mi mm mo mu my na ne no nu od oe of oh oi ok om on op or os ow ox oy pa pe pi po qi re sh si so ta te ti to uh um un up us ut we wo xi xu ya ye yo za".split()
for w in TWO:
    tier.setdefault(w, 70)
# Single letters and abbreviations-like two-letter entries that SCOWL includes but games reject
for w in list(tier):
    if len(w) == 2 and w not in TWO: del tier[w]

# Well-known word-game words SCOWL leaves out (mostly Q-without-U and short Z/X/J plays).
GAME = """qat qats qaid qaids qoph qophs qadi qadis faqir faqirs tranq tranqs qindar qindars qintar qintars suq suqs
qanat qanats niqab niqabs sheqel sheqels mbaqanga zax zas zek zeks zin zins zoa jeu jeux xu xis oxo
""".split()
for w in GAME:
    tier.setdefault(w, 70)
# Tier corrections: modern everyday words SCOWL rates as rarer, and contractions-without-apostrophe it rates as common.
PROMOTE = "app apps online website websites ok emoji emojis selfie selfies email emails blog blogs podcast podcasts smartphone smartphones wifi".split()
DEMOTE = "hes mes mys shes ins ons ers ems ens ess ids oes ays".split()
for w in PROMOTE:
    if w in tier: tier[w] = min(tier[w], 35)
    elif re.fullmatch(r"[a-z]+", w) and not blocked(w): tier[w] = 35
for w in DEMOTE:
    if w in tier: tier[w] = 70

(root / "data").mkdir(exist_ok=True)
(root / "data" / "words.json").write_text(json.dumps(tier, separators=(",", ":")))
out = []
for lvl in sorted(set(tier.values())):
    out.append(f"#{lvl}")
    out.extend(sorted(w for w, t in tier.items() if t == lvl))
# Content-hashed file name so browsers can cache the 1 MB list for a year and still pick up changes.
import hashlib
body = "\n".join(out)
h = hashlib.sha1(body.encode()).hexdigest()[:10]
for old in (root / "public").glob("words*.txt"): old.unlink()
(root / "public" / f"words.{h}.txt").write_text(body)
(root / "lib" / "dictFile.ts").write_text(f'// Generated by scripts/build-dict.py\nexport const DICT_FILE = "/words.{h}.txt";\n')
print(len(tier), "words")
